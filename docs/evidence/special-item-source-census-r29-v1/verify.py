"""Independent archive and local secret review; no engine, product or test imports."""
import gzip
import hashlib
import io
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SOURCE = ROOT / '.runtime/special-item-census-r29-v1'
OUTPUT = HERE / 'verification.json'
assert not OUTPUT.exists()


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


index = json.loads((HERE / 'index.json').read_bytes())
raws, rows = {}, []
for reference in index['references']:
    assert '/' not in reference['path'], 'Only top-level receipt originals are archived'
    packed = (HERE / reference['object']).read_bytes()
    obj = index['objects'][reference['raw_sha256']]
    assert sha(packed) == obj['stored_sha256'] and len(packed) == obj['stored_bytes']
    raw = gzip.decompress(packed)
    assert sha(raw) == reference['raw_sha256'] and len(raw) == reference['raw_bytes']
    assert raw == (SOURCE / reference['path']).read_bytes()
    target = io.BytesIO()
    with gzip.GzipFile(filename='', mode='wb', fileobj=target, mtime=0, compresslevel=9) as output:
        output.write(raw)
    assert target.getvalue() == packed
    raws[reference['path']] = raw
    rows.append({'path': reference['path'], 'raw_sha256': sha(raw), 'stored_sha256': sha(packed),
                 'original_bytes_equal': True, 'deterministic_recompression_equal': True})
assert len(raws) == 23 and len(index['objects']) == 22
assert {path.name for path in SOURCE.iterdir() if path.is_file()} == set(raws)
delivery = json.loads(raws['delivery-index.json'])
assert sha(raws['final-review.json']) == delivery['final_review']['sha256']
for name, expected in delivery['files'].items():
    raw = raws['special_item_capabilities_nemc_3.10.0.420447.json'] if name.startswith('fixture-root/') else raws[name]
    assert sha(raw) == expected['sha256'] and len(raw) == expected['bytes']


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for key, item in value.items():
            yield from strings(key)
            yield from strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from strings(item)


patterns = {'api_token': r'\bsk-[A-Za-z0-9_-]{20,}',
    'github_token': r'\b(?:gh[pousr]_[A-Za-z0-9]{25,}|github_pat_[A-Za-z0-9_]{25,})',
    'aws_access_key': r'\b(?:AKIA|ASIA)[A-Z0-9]{16}\b',
    'bearer_token': r'(?i)\bbearer\s+[A-Za-z0-9._~+/-]{20,}',
    'private_key': r'-----BEGIN (?:[A-Z0-9 ]+ )?PRIVATE KEY-----',
    'credential_url': r'\bhttps?://[^/\s:@]{1,80}:[^/\s@]{8,}@',
    'credential_assignment': r'''(?i)(?:api[_-]?key|secret[_-]?key|access[_-]?token|password)\s*[:=]\s*["']([A-Za-z0-9/+_.-]{20,})["']'''}
scan_inputs = {'original/' + name: raw for name, raw in raws.items()}
for path in HERE.iterdir():
    if path.is_file() and path.suffix != '.gz':
        scan_inputs['package/' + path.name] = path.read_bytes()
matches, decoded_strings = [], 0
for name, raw in scan_inputs.items():
    values = [raw.decode('utf-8', 'replace')]
    try:
        decoded = list(strings(json.loads(raw)))
        decoded_strings += len(decoded)
        values.extend(decoded)
    except (ValueError, UnicodeError):
        pass
    for kind, expression in patterns.items():
        if any(re.search(expression, text) for text in values):
            matches.append({'path': name, 'kind': kind})
assert not matches, matches
links = []
for target in re.findall(r'\[[^\]]*\]\(([^)]+)\)', (HERE / 'README.md').read_text(encoding='utf-8')):
    assert not re.match(r'\w+://', target)
    path = (HERE / target.split('#')[0]).resolve()
    assert path.is_file() or path == OUTPUT
    links.append(target)
for path in HERE.iterdir():
    if path.is_file() and path.suffix != '.gz':
        assert all(line == line.rstrip() for line in path.read_text(encoding='utf-8').splitlines()), path
result = {'schema': 1, 'passed': True, 'new_process': True, 'originals_checked': 23, 'objects_checked': 22,
    'raw_storage_sha_and_lengths_checked': True, 'deterministic_gzip_roundtrip': True,
    'original_top_level_bytes_unchanged': True, 'delivery_and_final_review_bindings_checked': True,
    'fixture_alias_validation': 'Only delivery-declared SHA equality to archived top-level generated bytes; fixture-root subtree not accessed',
    'rows': rows, 'relative_links_checked': links, 'text_whitespace_checked': True,
    'credential_scan': {'matches': 0, 'decoded_json_strings': decoded_strings, 'pattern_types': sorted(patterns),
        'scope': '23 raw originals plus current package text metadata; output itself excluded',
        'inputs': [{'path': name, 'sha256': sha(raw), 'bytes': len(raw)} for name, raw in sorted(scan_inputs.items())]},
    'engine_assets_executable_or_fixture_subtree_read': False, 'large_project_copied': False,
    'original_tests_generation_or_check_repeated': False, 'product_imported': False,
    'MC_RPC_GPU_used': False, 'default_census_created': False, 'old_skip_receipts_rewritten': False,
    'production_qualified': False, 'manual_issues_closed': 0}
OUTPUT.write_text(json.dumps(result, ensure_ascii=True, sort_keys=True, indent=2) + '\n', encoding='utf-8')
assert all((HERE / target.split('#')[0]).is_file() for target in links)
print(json.dumps({'passed': True, 'originals': 23, 'objects': 22, 'links': len(links),
                  'credential_scan_inputs': len(scan_inputs), 'credential_matches': 0}, sort_keys=True))
