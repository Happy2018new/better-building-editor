"""Verify reviewed product evidence and generate the versioned cauldron gate.

The ordinary-water appearance is an explicit biome preset style. This script
does not claim exact native parity, nor infer visual acceptance from publication.
"""
import argparse
import hashlib
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]
MODULE = 'behavior_pack/modern_projection/projection/'
IMPLEMENTATION = tuple(MODULE + name + '.py' for name in (
    'cauldron_appearance', 'cauldron_native_data', 'cauldron_preview',
    'cauldron_profile', 'cauldron_projection', 'cauldron_render_plan',
    'debug_cauldron_blueprints', 'liquid_preview', 'liquid_projection',
    'liquid_render_plan', 'liquid_transport', 'biomes'))
REPORTS = ('final-matrix-v1.json', 'final-extras-v1.json',
           'final-visibility-gallery-v1.json', 'default-biome-smoke-v2.json')
GATES = ('editor', 'projection_full', 'projection_missing', 'geometry', 'colors',
         'animation', 'occupancy', 'visibility', 'gallery', 'lifecycle', 'biome', 'default_path')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def identity(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode('ascii')).hexdigest()


def write(path, value):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,sort_keys=True,indent=2)+'\n',encoding='ascii')


def write_module(path, values):
    content = '"""Generated by tools/qualify_cauldron_r15.py; do not edit."""\n'
    content += ''.join('%s = %s\n' % (key,pprint.pformat(value,width=100,sort_dicts=True))
                       for key,value in values)
    path.write_text(content,encoding='ascii',newline='\n')


def capture_path(evidence, original):
    local = evidence/Path(original).name
    return local if local.exists() else Path(original)


def validate_sources(project, reports, contract):
    owned = dict((relative,digest(project/relative)) for relative in IMPLEMENTATION)
    resources = contract['output_sha256']
    for relative, expected in resources.items():
        if relative in ('resource_pack/models/netease_models.json','resource_pack/materials/entity.material'):
            continue
        if digest(project/relative) != expected:
            raise ValueError('Installed cauldron resource differs: '+relative)
    models = json.loads((project/'resource_pack/models/netease_models.json').read_bytes())
    materials = json.loads((project/'resource_pack/materials/entity.material').read_bytes())['materials']
    if (any(models.get(key) != value for key,value in contract['models'].items()) or
            any(materials.get(key) != value for key,value in contract['materials'].items())):
        raise ValueError('Installed cauldron registrations differ from the generated contract')
    for report in reports:
        for relative, expected in owned.items():
            if report['source_sha256'].get(relative) != expected:
                raise ValueError('Visible qualification belongs to a different implementation: '+relative)
        for relative, expected in resources.items():
            if relative not in ('resource_pack/models/netease_models.json','resource_pack/materials/entity.material'):
                if report['source_sha256'].get(relative) != expected:
                    raise ValueError('Visible qualification used different cauldron artwork: '+relative)
    return owned


def qualify(project, evidence, accepted):
    reports = [json.loads((evidence/name).read_bytes()) for name in REPORTS]
    for report in reports:
        if (report['completed'] is not True or report['restored'] is not True or
                report['source_unchanged'] is not True or report['cleanup_errors'] or
                report['fixture'] != 'test.entities.cauldrons'):
            raise ValueError('Cauldron runtime capture failed or did not restore')
        for capture in report['captures'].values():
            if (capture.get('ok') is not True or capture.get('reliable') is not True or
                    capture.get('agent_activation_allowed') is not False or
                    capture.get('activation_fallback') is not False or
                    digest(capture_path(evidence,capture['path'])) != capture['sha256']):
                raise ValueError('Cauldron capture is unreliable, foreground-activated, or changed')
    matrix, extras, visibility, default = reports
    matrix_analysis = json.loads((evidence/'final-matrix-v1-analysis.json').read_bytes())
    extras_analysis = json.loads((evidence/'final-extras-v1-analysis.json').read_bytes())
    for report,name,analysis in ((matrix,REPORTS[0],matrix_analysis),(extras,REPORTS[1],extras_analysis)):
        if analysis['report_sha256'] != digest(evidence/name):
            raise ValueError('Pixel analysis refers to a different runtime capture')
        for row in analysis['rows'].values():
            if row['content_pixels'] < 80:
                raise ValueError('No independently visible cauldron contents')
    for route in ('editor','full','missing'):
        levels = [matrix_analysis['rows']['%s_lava%d_filled' % (route,level)] for level in range(1,7)]
        if any(left['bounds'][1] <= right['bounds'][1] or
               left['content_pixels'] >= right['content_pixels'] for left,right in zip(levels,levels[1:])):
            raise ValueError('Six observed cauldron fill levels are not increasing')
        for case in ('lava6','custom_red','potion_43_0','water6','powder_snow6'):
            label=route+'_'+case+'_filled'
            pixel=extras_analysis['rows'][label]
            fraction=pixel['temporal_changed_fraction']
            if pixel['temporal_samples'] < 80 or (fraction != 0. if case=='powder_snow6' else fraction < .03):
                raise ValueError('Cauldron animated/static texture did not behave as expected: '+label)
    for case in ('lava6','custom_red','potion_43_0','water6','powder_snow6'):
        label='missing_'+case+'_filled'
        occupied,restored = (extras['extras'][label+'_'+mode] for mode in ('occupied','restored'))
        if (occupied['occupancy']['rendered_keep'] & 1 or occupied['liquid_groups'] or
                not restored['occupancy']['rendered_keep'] & 1 or not restored['liquid_groups']):
            raise ValueError('Occupied cauldron did not hide and restore')
    for case in ('lava6','water6'):
        for mode in ('section','hidden','restored'):
            state=visibility['extras']['editor_'+case+'_filled_'+mode]
            if (bool(state['cauldron']['groups']) != (mode=='restored') or
                    sum(row['common_cells'] for row in state['parts']) != (2 if mode=='restored' else 1)):
                raise ValueError('Cauldron shell and top disagree under visibility controls')
    gallery=visibility['rows']['editor_gallery_filled']
    if (gallery['source']['expected_cauldron_groups'] != 33 or
            len(gallery['ready']['cauldron']['groups']) != 33 or gallery['ready']['cauldron']['error']):
        raise ValueError('Public cauldron gallery failed to publish every surface')
    if default['profile']['default_enabled'] is not True:
        raise ValueError('Default Session did not own the qualified cauldron profile')
    biome_analysis=json.loads((evidence/'default-biome-analysis.json').read_bytes())
    if (biome_analysis['report_sha256'] != digest(evidence/REPORTS[3]) or
            biome_analysis['default_profile'] is not True):
        raise ValueError('Biome visual evidence differs from the default-path capture')
    for route in ('editor','full','missing'):
        pixels={}
        for biome in ('plains','swampland'):
            label=route+'_water6_filled_biome_'+biome
            changed=default['extras'][label]
            state=changed['ready']
            color=changed['changed']['color']
            expected=color[0]*65536+color[1]*256+color[2]
            groups=(state['cauldron']['groups'] if route=='editor' else
                    [row['group'] for row in state['liquid_groups']])
            if (state['biome'] != biome or not groups or
                    any(group[3][3][2] != expected for group in groups)):
                raise ValueError('Actual cauldron group did not follow the document biome')
            row=biome_analysis['rows'][label]
            if row['samples'] < 80 or row['capture_sha256'] != default['captures'][label]['sha256']:
                raise ValueError('Biome visual samples are too small or stale')
            pixels[biome]=row['rgb_median']
        if (pixels['plains'][2]<=pixels['plains'][1] or
                pixels['swampland'][1]<=pixels['swampland'][2] or
                sum(abs(left-right) for left,right in zip(pixels['plains'],pixels['swampland'])) < 36.):
            raise ValueError('Visible cauldron RGB did not change to the requested biome preset')
    contract_path=project/'tools/data/cauldron_resource_contract_nemc310_v1.json'
    contract=json.loads(contract_path.read_bytes())
    native_path=project/'tools/data/cauldron_native_nemc310_v1.json'
    if contract['measurement_sha256'] != digest(native_path):
        raise ValueError('Generated cauldron geometry belongs to different native measurements')
    owned=validate_sources(project,reports,contract)
    compact_sources={name:digest(evidence/name) for name in REPORTS}
    for name in ('final-matrix-v1-analysis.json','final-extras-v1-analysis.json',
                 'final-matrix-v1-analysis.png','final-extras-v1-analysis.png',
                 'default-biome-analysis.json','default-biome-analysis.png'):
        compact_sources[name]=digest(evidence/name)
    manifest={'schema_version':1,'engine_version':contract['engine_version'],
              'fixture':'test.entities.cauldrons','product_qualified':accepted,
              'exact_native_parity_claimed':False,
              'plain_water_style':'document_biome_world_water_v1',
              'resource_contract_sha256':digest(contract_path),'native_data_sha256':digest(native_path),
              'implementation_sha256':owned,'implementation_contract_sha256':identity(owned),
              'evidence_sha256':compact_sources,'gates':dict((gate,accepted) for gate in GATES),
              'counts':{'matrix_pairs':30,'animated_pairs':12,'static_pairs':3,
                        'occupied_restore_cases':5,'visibility_cases':2,'public_gallery_cases':33,
                        'default_biome_routes':3},
              'limits':['Ordinary water uses the document biome preset appearance.',
                        'Individual projection captures cover ten cases, not all 33 gallery cases.',
                        'Malformed or future cauldron appearances retain the native route.',
                        'Qualification covers the declared cauldron owner and resources; shared integration has separate tests.']}
    write(evidence/'qualification.json',manifest)
    module=project/MODULE
    write_module(module/'cauldron_resource_data.py',(
        ('SCHEMA_VERSION',1),('ENGINE_VERSION',contract['engine_version']),
        ('RESOURCE_CONTRACT_SHA256',manifest['resource_contract_sha256']),
        ('IMPLEMENTATION_CONTRACT_SHA256',manifest['implementation_contract_sha256'])))
    write_module(module/'cauldron_qualification_data.py',(
        ('SCHEMA_VERSION',1),('PRODUCT_QUALIFIED',accepted),
        ('QUALIFICATION_SHA256',digest(evidence/'qualification.json')),
        ('QUALIFICATION_RESOURCE_CONTRACT_SHA256',manifest['resource_contract_sha256']),
        ('QUALIFICATION_IMPLEMENTATION_CONTRACT_SHA256',manifest['implementation_contract_sha256']),
        ('QUALIFICATION_NATIVE_DATA_SHA256',manifest['native_data_sha256']),
        ('GATES',manifest['gates'])))
    return manifest


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project',type=Path,default=ROOT)
    parser.add_argument('--evidence',type=Path,default=ROOT/'docs/evidence/cauldron-product-r15')
    parser.add_argument('--accept-reviewed-product',action='store_true')
    args=parser.parse_args()
    value=qualify(args.project,args.evidence,args.accept_reviewed_product)
    print(json.dumps({'qualified':value['product_qualified'],'counts':value['counts']}))


if __name__=='__main__':
    main()
