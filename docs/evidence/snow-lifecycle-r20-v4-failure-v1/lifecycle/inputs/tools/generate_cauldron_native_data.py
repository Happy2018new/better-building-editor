"""Generate the runtime cauldron data only from hash-checked native evidence."""
import argparse
import hashlib
import json
from pathlib import Path
import pprint


ROOT = Path(__file__).resolve().parents[1]


def generate(source, evidence, output):
    raw = source.read_bytes()
    data = json.loads(raw)
    if (data.get('schema_version') != 1 or
            data.get('engine_version') != '3.10.0.420447' or
            data.get('geometry_measured') is not True or
            data.get('custom_rgb_measured') is not True):
        raise ValueError('Expected measured native cauldron schema 1')
    for relative, expected in data['sources'].items():
        path = (evidence / relative).resolve(strict=True)
        if not path.is_relative_to(evidence.resolve(strict=True)):
            raise ValueError('Cauldron evidence path escapes its root')
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise ValueError('Cauldron evidence changed: ' + relative)
    identity = hashlib.sha256(json.dumps(data['sources'],sort_keys=True,separators=(',',':')).encode('ascii')).hexdigest()
    if data.get('evidence_sha256') != identity:
        raise ValueError('Cauldron evidence identity differs from its checked sources')
    content = ('"""Generated by tools/generate_cauldron_native_data.py; do not edit."""\n'
               'SOURCE_SHA256 = %r\nDATA = %s\n' %
               (hashlib.sha256(raw).hexdigest(), pprint.pformat(data, width=100, sort_dicts=True)))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding='ascii', newline='\n')
    return {'source_sha256': hashlib.sha256(raw).hexdigest(),
            'output_sha256': hashlib.sha256(content.encode('ascii')).hexdigest(),
            'evidence_files': len(data['sources']),
            'product_acceptance_claimed': data.get('product_acceptance_claimed') is True}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'tools/data/cauldron_native_nemc310_v1.json')
    parser.add_argument('--evidence', type=Path, default=ROOT/'docs/evidence/cauldron-surface-r15')
    parser.add_argument('--output', type=Path,
                        default=ROOT/'behavior_pack/modern_projection/projection/cauldron_native_data.py')
    args = parser.parse_args()
    print(json.dumps(generate(args.source, args.evidence, args.output), sort_keys=True))


if __name__ == '__main__':
    main()
