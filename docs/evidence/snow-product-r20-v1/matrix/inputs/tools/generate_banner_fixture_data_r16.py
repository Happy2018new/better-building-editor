"""Package real item-placed banner observations for the public debug gallery."""
import base64
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/evidence/native-render-profile-r15/102-real-banner-payloads/report.json'
OUTPUT = ROOT / 'behavior_pack/modern_projection/projection/banner_fixture_data.py'


def main():
    report = json.loads(SOURCE.read_bytes())
    rows = []
    for saved, actor in zip(report['setup']['rows'], report['palette']['rows']):
        assert saved['name'] == actor['name'] and saved['pos'] == actor['pos']
        rows.append({'name': saved['name'], 'pos': saved['pos'], 'states': saved['states'],
                     'nbt': saved['nbt'], 'actor': actor['actor']})
    assert len(rows) == 6 and report['palette']['engine'] == '3.10.0.420447'
    packed = base64.b64encode(zlib.compress(json.dumps(rows, sort_keys=True, separators=(',', ':')).encode('ascii'), 9)).decode('ascii')
    content = ('"""Generated by tools/generate_banner_fixture_data_r16.py; do not edit."""\n'
               "SCHEMA_VERSION = 1\nENGINE_VERSION = '3.10.0.420447'\n"
               "SOURCE_SHA256 = %r\nROWS = %r\n" % (hashlib.sha256(SOURCE.read_bytes()).hexdigest(), packed))
    OUTPUT.write_text(content, encoding='ascii', newline='\n')
    print(json.dumps({'rows': len(rows), 'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest()}))


if __name__ == '__main__':
    main()
