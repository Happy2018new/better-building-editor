"""Retain the native decorated-pot four-direction render observations."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'behavior_pack/modern_projection'))
from projection import block_registry as registry


def generate(source,target,snapshot,check):
    raw=source.read_bytes()
    data=json.loads(raw)
    native=data.get('native',{})
    if (data.get('schema')!=1 or not data.get('completed') or not data.get('cleanup',{}).get('cleaned') or
            native.get('game_version')!=registry.source_version() or native.get('palette_sha256')!=registry.fingerprint()):
        raise ValueError('A restored decorated-pot capture matching the registry is required')
    observations=[]
    seen=set()
    for row in data['client']['rows']:
        value=(row['name'],row['aux'])
        if row['name']!='minecraft:decorated_pot' or row['block']!={'name':row['name'],'aux':row['aux']}:
            raise ValueError('Decorated-pot native state mismatch')
        actor=next(iter(row['palette']['actor'][row['name']].values()))
        states=registry.states(value)
        if actor['direction']!=states['direction'] or row['palette']['states'][0]['value']!=states:
            raise ValueError('Decorated-pot native direction mapping changed')
        seen.add(value[1])
        observations.append({'material':list(value),'states':states,'actor':actor})
    if seen!=set(registry.aux_values('minecraft:decorated_pot')):
        raise ValueError('Expected every native decorated-pot direction')
    snapshot_data={'schema_version':1,'game_version':registry.source_version(),'palette_sha256':registry.fingerprint(),
                   'source_sha256':hashlib.sha256(raw).hexdigest(),'observations':observations,
                   'scope':'native renderer direction; nondefault sherd mapping and GPU acceptance separate'}
    snapshot_text=json.dumps(snapshot_data,ensure_ascii=True,sort_keys=True,indent=2)+'\n'
    text='\n'.join(('# Generated by tools/generate_native_pot_poses.py; do not edit.',
        'from __future__ import unicode_literals','SCHEMA_VERSION = 1',
        'SOURCE_VERSION = '+repr(registry.source_version()),'PALETTE_SHA256 = '+repr(registry.fingerprint()),
        'SOURCE_SHA256 = '+repr(hashlib.sha256(snapshot_text.encode('ascii')).hexdigest()),
        'TEMPLATE = '+repr(observations[0]['actor']),''))
    for path,content in ((target,text),(snapshot,snapshot_text)):
        if check:
            if not path.exists() or path.read_text(encoding='ascii')!=content:raise ValueError('Stale native pot poses: '+str(path))
        else:path.write_text(content,encoding='ascii')
    print('Native decorated pots: %d direction observations' % len(observations))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source',type=Path)
    parser.add_argument('--target',type=Path,default=ROOT/'behavior_pack/modern_projection/projection/native_pot_data.py')
    parser.add_argument('--snapshot',type=Path,default=ROOT/'tools/data/native_pot_poses_nemc_3.9.0.401155.json')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    generate(args.source,args.target,args.snapshot,args.check)
