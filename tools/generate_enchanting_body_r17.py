"""Stage a native-textured table body without the Combine Y offset.

This is an isolated candidate. It does not register a product routing change
or replace the real enchanting table. All six faces retain native texels.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

from PIL import Image

IDENTIFIER = 'modern_projection:preview_enchanting_body'
TEXTURE = 'modern_projection_enchanting_body'


def write_json(path, data, sort_keys=True):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=True, indent=2, sort_keys=sort_keys) + '\n',
                    encoding='ascii', newline='\n')


def generate(native, output, project=None):
    output.mkdir(parents=True, exist_ok=False)
    version = native.parent.name
    if not re.fullmatch(r'\d+\.\d+\.\d+\.\d+', version):
        raise ValueError('Native data path must identify the installed engine version')
    root = Path(__file__).resolve().parents[1]
    registry = json.loads((root / 'tools/data/block_registry_manifest.json').read_bytes())
    original = native / 'resource_packs/vanilla'
    definition = json.loads((original / 'blocks.json').read_bytes())['enchanting_table']
    expected = {'up': 'enchanting_table_top', 'down': 'enchanting_table_bottom',
                'side': 'enchanting_table_side'}
    if definition.get('textures') != expected:
        raise ValueError('Native enchanting table texture bindings changed')
    atlas = Image.new('RGBA', (64, 16), (0, 0, 0, 0))
    sources = {}
    for index, part in enumerate(('top', 'bottom', 'side')):
        path = original / ('textures/blocks/enchanting_table_' + part + '.png')
        with Image.open(path) as texture:
            if texture.size != (16, 16):
                raise ValueError('Native enchanting table artwork layout changed')
            atlas.paste(texture.convert('RGBA'), (index*16, 0))
        sources[path.relative_to(native).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    texture_path = output / ('resource_pack/textures/blocks/' + TEXTURE + '.png')
    texture_path.parent.mkdir(parents=True)
    atlas.save(texture_path)
    uv = {face: {'uv': [32, 4], 'uv_size': [16, 12]}
          for face in ('north', 'south', 'east', 'west')}
    uv.update(up={'uv': [0, 0], 'uv_size': [16, 16]},
              down={'uv': [16, 0], 'uv_size': [16, 16]})
    geometry = {'format_version': '1.13.0', 'netease:block_geometry': {
        'description': {'identifier': IDENTIFIER, 'textures': [TEXTURE],
                        'textures_descriptions': [{'width': 64, 'length': 16}], 'use_ao': False},
        'bones': [{'name': 'table', 'pivot': [-8, 8, 8], 'rotation': [0, 0, 0],
                   'cubes': [{'origin': [-16, 0, 0], 'size': [16, 12, 16], 'uv': uv}]}],
    }}
    behavior = {'format_version': '1.10.0', 'minecraft:block': {
        'description': {'identifier': IDENTIFIER, 'register_to_creative_menu': False},
        'components': {'netease:render_layer': {'value': 'alpha'},
                       'netease:no_crop_face_block': {},
                       'minecraft:block_light_absorption': {'value': 0}},
    }}
    write_json(output / 'resource_pack/models/netease_block/preview_enchanting_body.json', geometry)
    write_json(output / 'behavior_pack/netease_blocks/preview_enchanting_body.json', behavior)
    data_path = output / 'behavior_pack/modern_projection/projection/static_table_data.py'
    data_path.parent.mkdir(parents=True, exist_ok=True)
    data_path.write_text(
        '# Generated by tools/generate_enchanting_body_r17.py; do not edit.\n'
        'SCHEMA_VERSION = 1\nSOURCE_VERSION = %r\nPALETTE_SHA256 = %r\n'
        'ENGINE_SOURCE_VERSION = %r\nPROXY = %r\n' % (
            registry['game_version'], registry['source_sha256'].lower(), version, IDENTIFIER),
        encoding='ascii', newline='\n')
    blocks = {IDENTIFIER: {'netease_model': IDENTIFIER, 'sound': 'stone'}}
    textures = {TEXTURE: {'textures': 'textures/blocks/' + TEXTURE}}
    write_json(output / 'blocks.patch.json', blocks)
    write_json(output / 'terrain_texture.patch.json', textures)
    contract = {'schema': 1, 'engine_version': version, 'product_qualified': False,
                'identifier': IDENTIFIER, 'source_sha256': sources,
                'shape': {'origin': [0, 0, 0], 'extent': [1., .75, 1.]},
                'native_body_offset_evidence': 'docs/evidence/enchanting-body-offset-r17-v1',
                'pixels': 'Three native 16x16 images copied without resampling into a 64x16 atlas.',
                'output_sha256': {p.relative_to(output).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                                  for p in output.rglob('*') if p.is_file()}}
    write_json(output / 'contract.json', contract)
    if project:
        for folder in ('behavior_pack', 'resource_pack'):
            for source in (output / folder).rglob('*'):
                if source.is_file():
                    target = project / source.relative_to(output)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(source, target)
        for relative, nested, patch in (('resource_pack/blocks.json', None, blocks),
                                         ('resource_pack/textures/terrain_texture.json', 'texture_data', textures)):
            target = project / relative
            registry = json.loads(target.read_bytes())
            destination = registry[nested] if nested else registry
            destination.update(patch)
            write_json(target, registry, sort_keys=False)
        write_json(project / 'tools/data/enchanting_body_candidate_r17.json', contract)
    print(json.dumps({'identifier': IDENTIFIER, 'product_qualified': False, 'output': str(output)}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-data', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--install-project', type=Path)
    args = parser.parse_args()
    generate(args.native_data, args.output, args.install_project)
