"""Build Chinese fallback labels from observed block-to-item aliases only."""
import argparse
import hashlib
import json
from pathlib import Path
from pprint import pformat
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'behavior_pack/modern_projection'))
from projection import block_registry as registry

SOURCE = ROOT / 'docs/evidence/block-labels-r23'
OUTPUT = ROOT / 'behavior_pack/modern_projection/projection/block_display_names_data.py'


def generate():
    server_path, client_path = SOURCE / 'server-aliases.json', SOURCE / 'client-names.json'
    server, client = (json.loads(path.read_bytes()) for path in (server_path, client_path))
    if (server['registry'] != registry.source_version() or
            server['palette_sha256'] != registry.fingerprint()):
        raise ValueError('Block label observations use another registry')
    names = dict((tuple(row['item']), row['info']['itemName']) for row in client['rows'])
    labels, aliases = {}, {}
    for row in server['rows']:
        value = tuple(row['material'])
        if (registry.canonical(value) != value or registry.states(value) != row['states']):
            raise ValueError('Observed block state differs: ' + repr(value))
        # Direction/half aux values are block state indices, not inventory
        # variants. The SDK maps some coral directions to other species.
        # Resolve one label from the name's default state, never from that aux.
        if value[1] != registry.DEFAULT_AUX[value[0]]:
            continue
        item = row['item']
        alias = (item['newItemName'], item['newAuxValue'])
        label = names[alias]
        if not label or label.startswith(('tile.', 'item.')):
            raise ValueError('Alias label is untranslated: ' + repr(alias))
        # The corresponding inventory item is a single slab; disambiguate the
        # double block in editor labels while retaining the native item wording.
        short = value[0].split(':', 1)[1]
        if (short.endswith('_double_slab') or
                (('double_' in short) and short.endswith('_slab'))):
            label = '\u53cc\u5c42' + label
        elif not short.endswith('_wall_fan'):
            raise ValueError('No reviewed display-label family: ' + short)
        labels[value[0]] = label
        aliases[value] = alias
    if set(labels) != set(row['material'][0] for row in server['rows']):
        raise ValueError('Missing a canonical default-state label')
    header = ('# -*- coding: utf-8 -*-\n'
              '# Generated by tools/generate_block_display_names.py; display labels only.\n'
              'from __future__ import unicode_literals\nSCHEMA_VERSION = 1\n')
    fields = [('SOURCE_VERSION', server['registry']),
              ('PALETTE_SHA256', server['palette_sha256']),
              ('OBSERVED_ENGINE_VERSION', client['engine']),
              ('OBSERVED_MINECRAFT_VERSION', client['runtime']),
              ('SOURCE_SHA256', dict((path.name, hashlib.sha256(path.read_bytes()).hexdigest())
                                     for path in (server_path, client_path))),
              ('ITEM_ALIASES', aliases), ('FALLBACK_NAMES', labels)]
    return header + ''.join(name + ' = ' + pformat(value, width=110, sort_dicts=True) + '\n'
                            for name, value in fields)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf8') != content:
            raise ValueError('Block display labels need regeneration')
    else:
        OUTPUT.write_text(content, encoding='utf8', newline='\n')
    print(json.dumps({'output': str(OUTPUT), 'check': args.check}))


if __name__ == '__main__':
    main()
