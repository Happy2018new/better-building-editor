"""Generate the portable, lazy block registry from a native block_palette.json."""
import argparse
import base64
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import zlib

ROOT = Path(__file__).resolve().parents[1]


def generate(source, source_version=None, check=False):
    if source_version is None:
        match = re.match(r'^nemc_(.+)$', source.stem, re.IGNORECASE)
        if not match:
            raise ValueError('Name palette dumps nemc_<version>.json or pass --source-version')
        source_version = 'NEMC '+match.group(1)
    raw = source.read_bytes()
    source_sha = hashlib.sha256(raw).hexdigest()
    records = json.loads(raw)['blocks']
    blocks = {}
    state_keys = set()
    for row in records:
        name, aux = row['name'], row['data']
        states = sorted((s['name'],s['type'],s['value']) for s in row['states'])
        assert all(t in ('byte','int','string') for k,t,v in states)
        assert aux not in blocks.setdefault(name, {})
        blocks[name][aux] = states
        state_keys.update(k for k, t, v in states)
    aliases = json.loads((ROOT/'tools/data/legacy_block_aliases.json').read_text(encoding='utf8'))
    compatible = {}
    for name,aux,target,data in aliases['rows']:
        if aux in blocks.get(name, {}):
            continue  # A real modern state always wins over item/drop aliases.
        assert data in blocks[target]
        compatible.setdefault(name, {})[aux] = (target,data)
    def pack(value):
        return base64.b64encode(zlib.compress(json.dumps(value,separators=(',',':')).encode('ascii'),9)).decode('ascii')
    lines = ['# Generated by tools/generate_block_registry.py; do not edit.',
             'from __future__ import unicode_literals',
             'SOURCE_SHA256 = '+repr(source_sha),
             'SOURCE_VERSION = '+repr(source_version),
             'RECORD_COUNT = '+str(len(records)), 'BLOCKS = {']
    for name,rows in sorted(blocks.items()):
        lines.append('    '+repr(name)+': '+repr(pack(sorted(rows.items())))+',')
    lines.extend(['}', 'DEFAULT_AUX = {'])
    for name,rows in sorted(blocks.items()):
        lines.append('    '+repr(name)+': '+str(min(rows))+',')
    lines.extend(['}', 'ALIASES = {'])
    for name,rows in sorted(compatible.items()):
        lines.append('    '+repr(name)+': '+repr(pack(sorted(rows.items())))+',')
    lines.extend(['}', ''])
    path = ROOT/'behavior_pack/modern_projection/projection/block_registry_data.py'
    generated = '\n'.join(lines)
    manifest_path = ROOT/'tools/data/block_registry_manifest.json'
    previous_manifest = json.loads(manifest_path.read_text(encoding='ascii')) if manifest_path.exists() else {}
    if (previous_manifest.get('source_sha256', '').lower() == source_sha and
            previous_manifest.get('game_version') == source_version):
        exported_at = previous_manifest['source_exported_at_utc']
    else:
        exported_at = datetime.fromtimestamp(source.stat().st_mtime, timezone.utc).replace(
            microsecond=0).isoformat().replace('+00:00', 'Z')
    try:
        source_name = str(source.resolve().relative_to(ROOT.resolve())).replace('\\', '/')
    except ValueError:
        source_name = source.name
    manifest = {
        'game_version': source_version,
        'source_file': source_name,
        'source_exported_at_utc': exported_at,
        'source_sha256': source_sha.upper(),
        'record_count': len(records),
        'name_count': len(blocks),
        'state_key_count': len(state_keys),
    }
    manifest_text = json.dumps(manifest, ensure_ascii=True, indent=2, sort_keys=True)+'\n'
    if check:
        stale = []
        if not path.exists() or path.read_text(encoding='ascii') != generated:
            stale.append(str(path.relative_to(ROOT)))
        if not manifest_path.exists() or manifest_path.read_text(encoding='ascii') != manifest_text:
            stale.append(str(manifest_path.relative_to(ROOT)))
        if stale:
            raise SystemExit('Generated registry is stale: '+', '.join(stale))
    else:
        path.write_text(generated,encoding='ascii')
        manifest_path.write_text(manifest_text,encoding='ascii')
    print('%d names, %d states, %d legacy aliases; %d bytes' % (
        len(blocks),len(records),sum(len(v) for v in compatible.values()),
        path.stat().st_size if path.exists() else len(generated)))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source',type=Path)
    parser.add_argument('--source-version',help='version label; otherwise inferred from nemc_<version>.json')
    parser.add_argument('--check',action='store_true',help='fail if generated files are stale')
    args=parser.parse_args()
    generate(args.source,args.source_version,args.check)
