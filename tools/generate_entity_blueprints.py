"""Generate compact native entity defaults for editing and debug blueprints."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'behavior_pack/modern_projection'))
from projection import block_registry as registry
from projection.cell import freeze
from projection.nbt_spatial import NBT_DIRECTIONS, root_payload, scalar


def snapshot_fingerprint(data):
    raw = json.dumps(data, ensure_ascii=True, sort_keys=True, separators=(',', ':')).encode('ascii')
    return hashlib.sha256(raw).hexdigest()


def generate_text(data, source_sha256):
    if (data.get('schema') != 1 or data.get('game_version') != registry.source_version() or
            data.get('palette_sha256', '').lower() != registry.fingerprint().lower() or
            not isinstance(data.get('block_entities'), dict)):
        raise ValueError('Entity defaults require a matching versioned native probe')
    rows, direction_names = [], []
    for name, row in sorted(data['block_entities'].items()):
        if not isinstance(row, dict) or type(row.get('aux')) is not int:
            raise ValueError('Native default needs an integer aux: ' + name)
        value = (name, row['aux'])
        if name not in registry.BLOCKS or registry.try_canonical(value) != value:
            raise ValueError('Native default is not in the current state table: ' + name)
        root = root_payload(row.get('nbt'))
        if root is None or not isinstance(scalar(root, 'id'), str) or not scalar(root, 'id'):
            raise ValueError('Native default needs an observed root entity ID: ' + name)
        if any(type(scalar(root, axis)) is not int for axis in ('x', 'y', 'z')):
            raise ValueError('Native default needs root integer coordinates: ' + name)
        if scalar(root, 'id') in NBT_DIRECTIONS:
            direction_names.append(name)
        raw = json.dumps([row['aux'], freeze(row['nbt'])], separators=(',', ':')).encode('ascii')
        rows.append((name, base64.b64encode(zlib.compress(raw, 9)).decode('ascii')))
    lines = ['# Generated by tools/generate_entity_blueprints.py; do not edit.',
             'from __future__ import unicode_literals', 'SCHEMA_VERSION = 1',
             'SOURCE_VERSION = ' + repr(data['game_version']),
             'PALETTE_SHA256 = ' + repr(data['palette_sha256'].lower()),
             'SOURCE_SHA256 = ' + repr(source_sha256),
             "SOURCE_HASH_FORMAT = 'canonical-json-v1'",
             'PROBE_METHOD = ' + repr(data.get('method', '')),
             'DEFAULTS = {']
    lines.extend('    %r: %r,' % row for row in rows)
    lines.extend(('}', 'ACTOR_DIRECTION_NAMES = frozenset(' + repr(tuple(direction_names)) + ')', ''))
    return '\n'.join(lines)


def snapshot(data, source_sha256):
    result = dict((key, data[key]) for key in (
        'schema', 'game_version', 'palette_sha256', 'method', 'tested_states',
        'verified_states', 'total_states', 'block_entities', 'block_entity_names'))
    result['native_probe_sha256'] = source_sha256
    return result


def field_audit(data):
    entities = {}
    for name, row in sorted(data['block_entities'].items()):
        root = root_payload(row['nbt'])
        identity = scalar(root, 'id')
        entry = entities.setdefault(identity, {'blocks': [], 'root_fields': {}})
        entry['blocks'].append(name)
        for field, value in sorted(root.items()):
            record = entry['root_fields'].setdefault(field, {'sdk_tag_types': [], 'python_types': []})
            tag_type = value.get('__type__') if isinstance(value, dict) else None
            actual = scalar(root, field)
            if tag_type is not None and tag_type not in record['sdk_tag_types']:
                record['sdk_tag_types'].append(tag_type)
            kind = type(actual).__name__
            if kind not in record['python_types']:
                record['python_types'].append(kind)
    return {'schema_version': 1, 'game_version': data['game_version'],
            'palette_sha256': data['palette_sha256'], 'entities': entities,
            'notes': ['Observed default fields and types do not establish transform semantics.',
                      'NBT root string identifiers do not verify numeric enum IDs.']}


def generate(source, target=None, check=False, snapshot_target=None, audit_target=None):
    raw = source.read_bytes()
    data = json.loads(raw)
    if snapshot_target is not None:
        data = snapshot(data, hashlib.sha256(raw).hexdigest())
        snapshot_text = json.dumps(data, ensure_ascii=True, indent=2, sort_keys=True) + '\n'
        snapshot_target.write_text(snapshot_text, encoding='ascii')
    text = generate_text(data, snapshot_fingerprint(data))
    target = target or ROOT / 'behavior_pack/modern_projection/projection/entity_defaults_data.py'
    if check:
        if not target.exists() or target.read_text(encoding='ascii') != text:
            raise ValueError('Generated native entity defaults are stale')
    else:
        target.write_text(text, encoding='ascii')
    if audit_target is not None:
        audit_target.write_text(json.dumps(field_audit(data), indent=2, sort_keys=True) + '\n',
                               encoding='ascii')
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--target', type=Path)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--snapshot', type=Path)
    parser.add_argument('--audit', type=Path)
    args = parser.parse_args()
    generate(args.source, args.target, args.check, args.snapshot, args.audit)
