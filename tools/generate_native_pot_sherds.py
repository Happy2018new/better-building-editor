"""Generate pot sherd field rules from restored target-native observations."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'behavior_pack/modern_projection'))
from projection import block_registry as registry


def generate(source, target, check=False):
    raw = source.read_bytes()
    data = json.loads(raw)
    if (data.get('schema_version') != 1 or not data.get('completed') or
            not data.get('restored') or not data.get('cleanup', {}).get('restored') or
            data.get('game_version') != registry.source_version() or
            data.get('palette_sha256') != registry.fingerprint()):
        raise ValueError('A restored native pot sherd capture matching the registry is required')
    fields = tuple('decoratedPotShredNames' + str(index) for index in range(4))
    seen = set()
    for row in data['rows']:
        aux = row['aux']
        requested = row['requested']
        expected = [{'__type__': 8, '__value__': value} for value in requested]
        actor = row.get('client', {}).get('actor', {})
        if (aux in seen or row['block'] != {'name': 'minecraft:decorated_pot', 'aux': aux} or
                len(requested) != 4 or len(set(requested)) != 4 or
                not row['accepted'] or row['nbt'].get('sherds') != expected or
                not row['client']['ready'] or actor.get('decoratedPotShredNamesSize') != 4 or
                [actor.get(field) for field in fields] != requested or
                actor.get('direction') != registry.states(('minecraft:decorated_pot', aux))['direction']):
            raise ValueError('Incomplete or conflicting pot sherd observation')
        seen.add(aux)
    if seen != set(registry.aux_values('minecraft:decorated_pot')):
        raise ValueError('Pot sherd capture must cover every legal direction')
    text = '\n'.join((
        '# Generated by tools/generate_native_pot_sherds.py; do not edit.',
        'from __future__ import unicode_literals', 'SCHEMA_VERSION = 1',
        'SOURCE_VERSION = ' + repr(registry.source_version()),
        'PALETTE_SHA256 = ' + repr(registry.fingerprint()),
        'SOURCE_SHA256 = ' + repr(hashlib.sha256(raw).hexdigest()),
        'SHERD_FIELDS = ' + repr(fields), ''))
    if check:
        if not target.exists() or target.read_text(encoding='ascii') != text:
            raise ValueError('Stale native pot sherd rules')
    else:
        target.write_text(text, encoding='ascii')
    print('Native pot sherds: four typed fields across %d directions' % len(seen))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'tools/data/native_pot_sherds_nemc_3.9.0.401155.json')
    parser.add_argument('--target', type=Path, default=ROOT / 'behavior_pack/modern_projection/projection/native_pot_sherd_data.py')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.source, args.target, args.check)
