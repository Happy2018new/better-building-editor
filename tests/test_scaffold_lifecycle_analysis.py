"""Lifecycle analysis keeps native timing distinct from support qualification."""
import copy
import importlib.util
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import analyze_scaffold_state_lifecycle as analysis

spec = importlib.util.spec_from_file_location('scaffold_lifecycle_host_fixture',
                                             ROOT / 'tests/test_scaffold_state_lifecycle.py')
fixture_module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fixture_module)


class LifecycleAnalysisTests(unittest.TestCase):
    def setUp(self):
        self.fixture = fixture_module.ScaffoldStateLifecycleTests()
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)

    def report(self):
        report = self.fixture.complete()
        probe = analysis.probe
        source = probe.digest(Path(probe.__file__).read_bytes())
        report['source_sha256'] = source
        report['start']['source_sha256'] = source
        report['native']['start']['source_sha256'] = source
        payload = probe.start_payload(self.fixture.identity, source, True)
        report['provenance']['native_payload_sha256'] = probe.digest(payload.encode('utf8'))
        return report

    def test_separates_autogenerated_upper_cell_from_early_normalization(self):
        result = analysis.analyze(self.report())
        rows = {row['id']: row for row in result['rows']}
        door = rows['door_direct_legacy']
        self.assertTrue(door['upper_exists_before_scaffold'])
        self.assertEqual('minecraft:acacia_door', door['upper_before_scaffold']['front']['name'])
        self.assertEqual('minecraft:scaffolding', door['upper_by_phase']['scaffold_written']['front']['name'])
        self.assertFalse(door['scaffold_write_changed_support'])
        self.assertTrue(rows['shelf_direct_legacy']['changed_before_scaffold'])
        self.assertFalse(rows['shelf_converted_semantic']['changed_before_scaffold'])
        self.assertFalse(rows['shelf_direct_legacy']['delayed_changed_support'])
        pairs = {pair['control']: pair for pair in result['direct_semantic_pairs']}
        self.assertTrue(all(pairs['shelf']['direct_and_semantic_differ'].values()))
        self.assertEqual({'editor': 'pending', 'full': 'pending', 'missing': 'pending'}, result['acceptance'])
        self.assertTrue(all(row['capability'].startswith('unknown_') for row in result['rows']))

    def test_native_support_changes_are_assigned_to_actual_write_or_delay(self):
        native = self.fixture.native
        original_write = native.SetBlockNew
        def write(pos, value, *args):
            returned = original_write(pos, value, *args)
            name = value['name'].decode('utf8') if isinstance(value['name'], bytes) else value['name']
            if name == 'minecraft:scaffolding':
                below = (pos[0], pos[1] - 1, pos[2])
                if native.GetBlockNew(below, 0)['name'] == 'minecraft:acacia_fence_gate':
                    native.states[below] = {'native_after_scaffold': True}
            return returned
        native.SetBlockNew = write
        result = analysis.analyze(self.report())
        gate = next(row for row in result['rows'] if row['id'] == 'gate_direct_legacy')
        self.assertTrue(gate['scaffold_write_changed_support'])
        self.assertFalse(gate['delayed_changed_support'])
        self.assertFalse(gate['changed_before_scaffold'])
        self.assertEqual({'native_after_scaffold': True}, gate['support_by_phase']['delayed_035']['states'])

    def test_rejects_unobserved_or_inconsistent_timing_without_upgrading_data(self):
        report = self.report()
        partial = copy.deepcopy(report)
        partial['native']['rows'][0]['samples'].pop()
        with self.assertRaises(ValueError):
            analysis.analyze(partial)
        inconsistent = copy.deepcopy(report)
        inconsistent['native']['rows'][0]['writes'][2]['before']['states'] = {'actual_typed_byte': False}
        with self.assertRaisesRegex(ValueError, 'upper cell changed'):
            analysis.analyze(inconsistent)

    def test_state_type_differences_remain_visible(self):
        report = self.report()
        row = report['native']['rows'][0]
        support = analysis.probe.cell_at(row['samples'][1], (0, 0, 0))
        support['states'] = {'native_byte': False}
        delayed = analysis.probe.cell_at(row['samples'][2], (0, 0, 0))
        delayed['states'] = {'native_byte': 0}
        result = analysis.analyze(report)['rows'][0]
        self.assertTrue(result['delayed_changed_support'])


if __name__ == '__main__':
    unittest.main()
